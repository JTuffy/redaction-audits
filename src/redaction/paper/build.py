"""Generated tables, compilation and the live preview for the paper in `paper/`.

The prose is written by hand. Code only writes `paper/generated/`: tables and number macros
built from the frozen data builds and the run ledger, so a number in the paper always matches
the run it came from. `compile_paper` runs Tectonic and writes `build/status.json` (time, errors,
section outline), which the viewer's Paper page polls to reload the PDF after each save.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, Final

from redaction.infra.log_setup import get_logger

log = get_logger(__name__)

SOURCES: Final = ("*.tex", "*.bib", "*.sty")
WORKING_SPLITS: Final = ("dev", "val", "test")
_SECTION = re.compile(r"\\section\*?\{([^}]*)\}")
_COMMENT = re.compile(r"(?<!\\)%.*$", re.MULTILINE)
# Commands whose arguments are not prose (and \todo notes, which aren't written yet).
_NON_PROSE = re.compile(
    r"\\(label|ref|eqref|autoref|cite[pt]?|input|include|begin|end|includegraphics|url|todo"
    r"|bibliography\w*|nocite)\*?(\[[^\]]*\])?\{[^}]*\}"
)
_COMMAND = re.compile(r"\\[A-Za-z]+\*?")


def find_tectonic() -> str | None:
    """Tectonic on PATH, or in the per-user install location on Windows."""
    found = shutil.which("tectonic")
    if found:
        return found
    local = Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "tectonic" / "tectonic.exe"
    return str(local) if local.is_file() else None


def _tex_escape(text: str) -> str:
    return re.sub(r"([_&%$#])", r"\\\1", text)


def _macro(*parts: str) -> str:
    r"""`\\LeakageTextRedaction` from ("leakage", "text_redaction"): letters only."""
    return "".join(w[0].upper() + w[1:] for p in parts for w in re.split(r"[^A-Za-z]+", p) if w)


def _latest_manifest(built_dir: Path, split: str) -> dict[str, Any] | None:
    latest = built_dir / split / "LATEST"
    if not latest.is_file():
        return None
    path = built_dir / split / latest.read_text(encoding="utf-8").strip() / "manifest.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def builds_table(built_dir: Path) -> str:
    """One row per split's current build: renderer, cues, kept of planned, labels."""
    rows = []
    for split in WORKING_SPLITS:
        m = _latest_manifest(built_dir, split)
        if m is None:
            continue
        labels = m.get("labels", {})
        stages = m["stages"]
        rows.append(
            f"{split} & \\texttt{{{m['version']}}} & {_tex_escape(m['renderer'])} & "
            f"{m.get('cues', 'verbatim')} & {stages['kept']}/{stages['planned']} & "
            f"{labels.get('violation', 0)} & {labels.get('red_herring', 0)} & "
            f"{labels.get('clean', 0)} \\\\"
        )
    return "\n".join(
        [
            "% Generated by `redaction paper tables` from data/built/*/LATEST. Do not edit.",
            "\\begin{tabular}{llllrrrr}",
            "\\toprule",
            "Split & Build & Renderer & Cues & Kept & Viol. & Herring & Clean \\\\",
            "\\midrule",
            *rows,
            "\\bottomrule",
            "\\end{tabular}",
            "",
        ]
    )


def _latest_run(ledger_dir: Path, kind: str) -> dict[str, Any] | None:
    ledger = ledger_dir / "ledger.jsonl"
    if not ledger.is_file():
        return None
    runs = [json.loads(line) for line in ledger.read_text(encoding="utf-8").splitlines() if line]
    runs = [r for r in runs if r.get("kind") == kind]
    return runs[-1] if runs else None


def _fmt(value: object) -> str:
    return f"{value:.2f}" if isinstance(value, float) else str(value)


def p1_table_and_macros(ledger_dir: Path) -> tuple[str, list[str]]:
    """The latest recorded P1 run: one row per policy, plus a macro per headline number."""
    run = _latest_run(ledger_dir, "p1")
    summary_path = ledger_dir / run["name"] / "summary.json" if run else None
    if run is None or summary_path is None or not summary_path.is_file():
        return "% No recorded P1 run yet.\n", []
    summaries: list[dict[str, Any]] = json.loads(summary_path.read_text(encoding="utf-8"))
    macros = [f"\\newcommand{{\\PoneRun}}{{\\texttt{{{_tex_escape(run['name'])}}}}}"]
    rows = []
    for s in summaries:
        policy = s["policy"]
        cells = {
            "Persistence": s["persistence"]["estimate"],
            "Leakage": s["leakage_mean"]["estimate"],
            "AurocEdited": s["auroc_edited"],
            "EvidenceLoss": s["evidence_loss"],
        }
        macros += [
            f"\\newcommand{{\\{_macro(name, policy)}}}{{{_fmt(v)}}}" for name, v in cells.items()
        ]
        low, high = s["leakage_mean"]["low"], s["leakage_mean"]["high"]
        rows.append(
            f"{_tex_escape(policy)} & {s['samples']} & {_fmt(s['auroc_edited'])} & "
            f"{_fmt(s['persistence']['estimate'])} & {_fmt(s['leakage_mean']['estimate'])} "
            f"[{_fmt(low)}, {_fmt(high)}] & {_fmt(s['evidence_loss'])} \\\\"
        )
    table = "\n".join(
        [
            f"% Generated by `redaction paper tables` from runs/{run['name']}. Do not edit.",
            "\\begin{tabular}{lrrrlr}",
            "\\toprule",
            "Policy & $n$ & AUROC (edited) & Persistence & Leakage [95\\% CI] & Evidence loss \\\\",
            "\\midrule",
            *rows,
            "\\bottomrule",
            "\\end{tabular}",
            "",
        ]
    )
    return table, macros


def write_generated(paper_dir: Path, *, built_dir: Path, ledger_dir: Path) -> list[Path]:
    """Rewrite everything under `paper/generated/`."""
    out = paper_dir / "generated"
    out.mkdir(parents=True, exist_ok=True)
    p1_table, macros = p1_table_and_macros(ledger_dir)
    files = {
        "builds.tex": builds_table(built_dir),
        "p1_pilot.tex": p1_table,
        "numbers.tex": "% Generated by `redaction paper tables`. Do not edit.\n"
        + "\n".join(macros)
        + "\n",
    }
    written = []
    for name, text in files.items():
        path = out / name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def _words(tex: str) -> int:
    text = _COMMAND.sub(" ", _NON_PROSE.sub(" ", _COMMENT.sub("", tex)))
    return len(re.findall(r"[A-Za-z][A-Za-z'-]*", text))


def outline(paper_dir: Path) -> list[dict[str, Any]]:
    """Each section file in reading order: its title and hand-written word count."""
    main = (paper_dir / "main.tex").read_text(encoding="utf-8")
    order = re.findall(r"^\s*\\input\{(sections/[^}]+)\}", main, re.MULTILINE)
    sections = []
    for ref in order:
        if ref.endswith("checklist"):  # the venue's template text, not ours
            continue
        path = paper_dir / (ref if ref.endswith(".tex") else f"{ref}.tex")
        if not path.is_file():
            continue
        tex = path.read_text(encoding="utf-8")
        titles = _SECTION.findall(tex)
        sections.append(
            {
                "file": path.relative_to(paper_dir).as_posix(),
                "title": titles[0] if titles else path.stem.replace("_", " ").title(),
                "words": _words(_SECTION.sub("", tex)),
            }
        )
    return sections


def _errors(output: str) -> list[str]:
    keep = [ln.strip() for ln in output.splitlines() if ln.startswith(("error:", "!"))]
    return keep[:12]


def compile_paper(paper_dir: Path, *, tectonic: str | None = None) -> dict[str, Any]:
    """Compile `main.tex` into `paper/build/` and write `build/status.json`."""
    build = paper_dir / "build"
    build.mkdir(exist_ok=True)
    exe = tectonic or find_tectonic()
    started = time.monotonic()
    if exe is None:
        ok, errors = False, ["Tectonic not found. Install it, or put it on PATH."]
    else:
        proc = subprocess.run(  # noqa: S603 - a fixed local binary on the repo's own sources
            [exe, "-X", "compile", "main.tex", "--outdir", "build", "--keep-logs"],
            cwd=paper_dir,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=False,
        )
        ok = proc.returncode == 0
        errors = [] if ok else (_errors(proc.stdout + proc.stderr) or ["compile failed"])
    status = {
        "built_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "ok": ok,
        "errors": errors,
        "seconds": round(time.monotonic() - started, 1),
        "pdf": (build / "main.pdf").is_file(),
        "outline": outline(paper_dir),
    }
    (build / "status.json").write_text(json.dumps(status, indent=1), encoding="utf-8")
    log.info("paper_compiled", ok=ok, errors=len(errors), seconds=status["seconds"])
    return status


def publish(paper_dir: Path, site_dir: Path) -> None:
    """Copy the PDF and status into the built site, so the Paper page picks them up."""
    target = site_dir / "paper"
    target.mkdir(parents=True, exist_ok=True)
    for name in ("main.pdf", "status.json"):
        source = paper_dir / "build" / name
        if source.is_file():
            shutil.copyfile(source, target / name)


def _snapshot(paper_dir: Path) -> dict[str, float]:
    files = [
        p
        for pattern in SOURCES
        for p in paper_dir.rglob(pattern)
        if "build" not in p.relative_to(paper_dir).parts
    ]
    return {str(p): p.stat().st_mtime for p in files}


def watch(
    paper_dir: Path,
    site_dir: Path,
    *,
    built_dir: Path,
    ledger_dir: Path,
    interval: float = 1.0,
) -> None:
    """Recompile and republish whenever a source changes (or the ledger gets a new run)."""
    ledger = ledger_dir / "ledger.jsonl"
    seen: dict[str, float] = {}
    ledger_seen = -1.0
    while True:
        ledger_now = ledger.stat().st_mtime if ledger.is_file() else 0.0
        if ledger_now != ledger_seen:
            write_generated(paper_dir, built_dir=built_dir, ledger_dir=ledger_dir)
            ledger_seen = ledger_now
        now = _snapshot(paper_dir)
        if now != seen:
            time.sleep(0.3)  # let an editor finish writing
            compile_paper(paper_dir)
            publish(paper_dir, site_dir)
            seen = _snapshot(paper_dir)
        time.sleep(interval)
